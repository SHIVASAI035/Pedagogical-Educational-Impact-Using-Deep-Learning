"""Administrator-only management and monitoring endpoints."""
from __future__ import annotations

import json
import os
import random

from flask import Blueprint, current_app, jsonify, request

from ..deep_learning import predictor
from ..extensions import db
from ..models import ClassRoom, Student, Teacher, User
from ..services.accounts import create_user, delete_user, get_user
from ..services.analytics import admin_overview
from ..utils.decorators import role_required
from ..utils.errors import ValidationError
from ..utils.validation import as_email, as_password, as_role, as_str, payload, require_fields
from ._helpers import paginated, search_users

bp = Blueprint("admin", __name__, url_prefix="/api/admin")


@bp.get("/stats")
@role_required("admin")
def stats():
    overview = admin_overview()
    overview["model"] = {
        "ready": predictor.is_ready(),
        "version": (predictor.metrics().get("model_version") if predictor.is_ready() else None),
    }
    return jsonify(overview)


@bp.get("/users")
@role_required("admin")
def list_users():
    role = request.args.get("role")
    if role and role not in {"admin", "teacher", "student"}:
        raise ValidationError("Invalid role filter.")
    query = search_users(User.query, role, request.args.get("search"))
    query = query.order_by(User.created_at.desc())
    return jsonify(paginated(query))


@bp.post("/users")
@role_required("admin")
def create_account():
    data = payload()
    require_fields(data, ["full_name", "email", "password", "role"])
    role = as_role(data["role"])
    user = create_user(
        full_name=as_str(data["full_name"], "full_name", max_len=120),
        email=as_email(data["email"]),
        password=as_password(data["password"]),
        role=role,
        roll_number=data.get("roll_number"),
        class_id=data.get("class_id"),
        guardian_name=data.get("guardian_name"),
        employee_code=data.get("employee_code"),
        department=data.get("department"),
        specialization=data.get("specialization"),
    )
    return jsonify(user.to_dict()), 201


@bp.put("/users/<int:user_id>")
@role_required("admin")
def update_account(user_id: int):
    user = get_user(user_id)
    data = payload()
    if "full_name" in data:
        user.full_name = as_str(data["full_name"], "full_name", max_len=120)
    if "is_active" in data:
        user.is_active = bool(data["is_active"])
    if data.get("password"):
        user.set_password(as_password(data["password"]))
    if "role" in data and data["role"] != user.role:
        raise ValidationError("Changing a user's role after creation is not supported.")
    db.session.commit()
    return jsonify(user.to_dict())


@bp.delete("/users/<int:user_id>")
@role_required("admin")
def remove_account(user_id: int):
    user = get_user(user_id)
    if user.role == "admin" and User.query.filter_by(role="admin", is_active=True).count() <= 1:
        raise ValidationError("The last active administrator account cannot be deleted.")
    delete_user(user)
    return jsonify({"message": "Account deleted."})


@bp.get("/model-metrics")
@role_required("admin")
def model_metrics():
    if not predictor.is_ready():
        return jsonify(
            {
                "ready": False,
                "message": "No trained model found. Train it from this page or run the CLI command.",
            }
        )
    metrics = predictor.metrics()
    metrics["ready"] = True
    return jsonify(metrics)


@bp.get("/structure")
@role_required("admin")
def structure():
    return jsonify(
        {
            "classes": [classroom.to_dict() for classroom in ClassRoom.query.all()],
            "teachers": [teacher.to_dict() for teacher in Teacher.query.all()],
            "students": [student.to_dict() for student in Student.query.all()],
        }
    )


@bp.get("/dataset")
@role_required("admin")
def dataset_summary():
    import pandas as pd

    from ..deep_learning.train_student_ann import FEATURES

    path = current_app.config["DATASET_PATH"]
    if not os.path.exists(path):
        return jsonify({"available": False, "message": "Dataset file not found."})
    frame = pd.read_csv(path)
    preview = json.loads(frame.head(10).to_json(orient="records"))
    summary = json.loads(frame.describe().round(2).to_json())
    return jsonify(
        {
            "available": True,
            "rows": int(len(frame)),
            "columns": list(frame.columns),
            "features": FEATURES,
            "synthetic": True,
            "missing_values": int(frame.isna().sum().sum()),
            "summary": summary,
            "preview": preview,
            "path": "backend/app/dataset/student_performance.csv",
            "note": (
                "Synthetic dataset generated by app/dataset/generate_dataset.py. "
                "Retrain the model after regenerating it."
            ),
        }
    )


@bp.post("/dataset/regenerate")
@role_required("admin")
def regenerate_dataset():
    from ..dataset.generate_dataset import write_dataset

    data = request.get_json(silent=True) or {}
    rows = data.get("rows", 4000)
    seed = data.get("seed", random.randint(1, 99999))
    try:
        rows = max(500, min(20000, int(rows)))
    except (TypeError, ValueError):
        raise ValidationError("'rows' must be an integer between 500 and 20000.") from None
    meta = write_dataset(rows=rows, seed=int(seed))
    meta["message"] = "Dataset regenerated. Retrain the model to use the new data."
    return jsonify(meta), 201
